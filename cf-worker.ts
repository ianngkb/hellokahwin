// Cloudflare Worker entry for HelloKahwin (wrangler.jsonc "main").
//
// Wraps the Worker that `opennextjs-cloudflare build` generates so a little of
// our own code runs around Next. Vercel never loads this file.
//
//   - HK_NOINDEX=1 (the workers.dev preview) stamps `X-Robots-Tag: noindex` on
//     every response, so the preview copy can never be indexed next to
//     hellokahwin.com. Next's own headers are left untouched.
//
// Scheduled jobs: none. vercel.json declares no crons, so there is no
// `scheduled` handler and no "triggers" block (docs/cloudflare.md, "Schedules").
//
// Excluded from tsconfig and eslint: .open-next/ only exists after a
// Cloudflare build, so the Vercel build cannot resolve the import below.

// @ts-ignore -- generated by `opennextjs-cloudflare build`
import openNextWorker from './.open-next/worker.js';

type Env = { HK_NOINDEX?: string } & Record<string, unknown>;
type Ctx = { waitUntil(promise: Promise<unknown>): void; passThroughOnException(): void };

export default {
  async fetch(request: Request, env: Env, ctx: Ctx): Promise<Response> {
    const response: Response = await openNextWorker.fetch(request, env, ctx);
    if (env.HK_NOINDEX !== '1') return response;
    const stamped = new Response(response.body, response);
    stamped.headers.set('x-robots-tag', 'noindex, nofollow');
    return stamped;
  },
};

