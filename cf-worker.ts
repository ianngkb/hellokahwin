// Cloudflare Worker entry for HelloKahwin (wrangler.jsonc "main").
//
// Wraps the Worker that `opennextjs-cloudflare build` generates so a little of
// our own code runs around Next. Vercel never loads this file.
//
//   - noindex: `X-Robots-Tag: noindex, nofollow` on every response when
//     HK_NOINDEX=1 (the read-only preview) and on every *.workers.dev request
//     (the production Worker keeps its workers.dev address for testing), so no
//     copy of the site ever competes with hellokahwin.com. Next's own headers
//     are left untouched.
//   - x-hk-build: the git SHA the version was built from (HK_BUILD_SHA, set by
//     cf-production.yml), so a deploy check can prove which version answered.
//   - scheduled: the nightly Google Search Console sync that Vercel Cron used
//     to call (`/api/cron/gsc-sync`, vercel.json). The Cron Trigger lives in
//     wrangler.jsonc env.production. It only does work when HK_CRON_ENABLED=1,
//     which is set at the domain switch in the same step Vercel's cron is
//     switched off, so the job never runs on both (docs/cloudflare.md).
//
// Excluded from tsconfig and eslint: .open-next/ only exists after a
// Cloudflare build, so the Vercel build cannot resolve the import below. The
// pure parts live in src/lib/cloudflare/worker-entry.ts, which is tested.

// @ts-ignore -- generated by `opennextjs-cloudflare build`
import openNextWorker from './.open-next/worker.js';
import {
  CRON_ROUTES,
  cronRequest,
  isCronEnabled,
  responseStamps,
  type WorkerEnv,
} from './src/lib/cloudflare/worker-entry';

type Ctx = { waitUntil(promise: Promise<unknown>): void; passThroughOnException(): void };
type ScheduledController = { cron: string; scheduledTime: number };

export default {
  async fetch(request: Request, env: WorkerEnv, ctx: Ctx): Promise<Response> {
    const response: Response = await openNextWorker.fetch(request, env, ctx);
    const stamps = responseStamps(request, env);
    if (!stamps) return response;
    const stamped = new Response(response.body, response);
    for (const [name, value] of Object.entries(stamps)) stamped.headers.set(name, value);
    return stamped;
  },

  async scheduled(controller: ScheduledController, env: WorkerEnv, ctx: Ctx): Promise<void> {
    if (!isCronEnabled(env)) {
      console.log(`[cron] ${controller.cron}: HK_CRON_ENABLED is not 1, skipped`);
      return;
    }
    const path = CRON_ROUTES[controller.cron];
    if (!path) {
      console.error(`[cron] no route for schedule "${controller.cron}"`);
      return;
    }
    // Through Next, exactly as Vercel Cron called it: a GET with the bearer
    // secret. Same route, same idempotent upserts, same logs.
    const request = cronRequest(path, env);
    ctx.waitUntil(
      Promise.resolve(openNextWorker.fetch(request, env, ctx)).then(async (res: Response) => {
        const body = await res.text();
        const line = `[cron] ${path} -> ${res.status} ${body.slice(0, 500)}`;
        if (res.ok) console.log(line);
        else console.error(line);
      }),
    );
  },
};

